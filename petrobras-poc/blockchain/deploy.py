import json
import os
from solcx import compile_standard, install_solc
from web3 import Web3
from web3.middleware import ExtraDataToPOAMiddleware

def compile_and_deploy():
    # Install specific solc version necessary to compile the contract
    print("Installing solc...")
    install_solc("0.8.0")
    print("Solc installed successfully.")

    # Path to the contract file
    current_dir = os.path.dirname(os.path.abspath(__file__))
    contract_path = os.path.join(current_dir, "contracts", "AccessControl.sol")
    
    with open(contract_path, "r") as file:
        contract_source = file.read()

    # Compile the contract
    print("Compiling contract AccessControl.sol...")
    compiled_sol = compile_standard(
        {
            "language": "Solidity",
            "sources": {"AccessControl.sol": {"content": contract_source}},
            "settings": {
                "outputSelection": {
                    "*": {
                        "*": ["abi", "metadata", "evm.bytecode", "evm.sourceMap"]
                    }
                }
            },
        },
        solc_version="0.8.0",
    )
    print("Contract compiled successfully.")

    # Extract bytecode and ABI from the compiled contract
    bytecode = compiled_sol["contracts"]["AccessControl.sol"]["AccessControl"]["evm"]["bytecode"]["object"]
    abi = compiled_sol["contracts"]["AccessControl.sol"]["AccessControl"]["abi"]

    # Connect to local test network (e.g., Hardhat or Ganache) on default port 8545
    w3 = Web3(Web3.HTTPProvider("http://127.0.0.1:7545"))
    w3.middleware_onion.inject(ExtraDataToPOAMiddleware, layer=0) # Necessary for some local networks like Ganache/Hardhat

    if not w3.is_connected():
        print("Failed to connect to local ethereum node. Make sure Ganache or Hardhat network is running at 127.0.0.1:7545")
        exit(1)

    print("Connected to local blockchain node.")

    # Use the first account generated by the local node as the Owner/Deployer
    deployer_account = w3.eth.accounts[0]
    w3.eth.default_account = deployer_account

    # Deploy the contract
    AccessControl = w3.eth.contract(abi=abi, bytecode=bytecode)

    print("Deploying contract...")
    tx_hash = AccessControl.constructor().transact()
    tx_receipt = w3.eth.wait_for_transaction_receipt(tx_hash)

    contract_address = tx_receipt.contractAddress
    print(f"Contract successfully deployed! Address: {contract_address}")

    # Set up the dummy device for our frontend testing.
    # We will use the second account available as the "smart glasses device"
    if len(w3.eth.accounts) > 1:
        dummy_device_address = w3.eth.accounts[1]
    else:
        # Create a new keypair specifically for testing
        test_account = w3.eth.account.create()
        dummy_device_address = test_account.address

    print(f"Authorizing the Smart Glasses Simulator device address: {dummy_device_address}")

    # Connect to the deployed contract instance to execute the authorization
    contract_instance = w3.eth.contract(address=contract_address, abi=abi)
    auth_tx_hash = contract_instance.functions.authorizeDevice(dummy_device_address).transact({"from": deployer_account})
    w3.eth.wait_for_transaction_receipt(auth_tx_hash)

    print("Device successfully added to authorized devices list (Zero Trust valid).")

    # Save ABI and Address to a configuration file that the backend can read
    output_data = {
        "address": contract_address,
        "abi": abi,
        "dummy_frontend_device": dummy_device_address
    }

    # Write output to the backend directory
    backend_dir = os.path.join(current_dir, "..", "backend")
    os.makedirs(backend_dir, exist_ok=True)
    output_path = os.path.join(backend_dir, "contract_data.json")

    with open(output_path, "w") as f:
        json.dump(output_data, f, indent=4)

    print(f"Execution complete. Contract data saved to {output_path}")

if __name__ == "__main__":
    compile_and_deploy()
